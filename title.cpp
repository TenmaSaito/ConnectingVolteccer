void CTitle::Start(void)
{
	// 仮置きでカメラを生成 (自動解放)
	// TODO : ここのカメラはタイトル用のカメラを作って置き換える事！
	CCamera *pCamera = new CCamera(CCamera::TYPE_TITLE);
	pCamera->Init(Vector3(0.0f, 0.0f, -100.0f));
	pCamera->SetFocus();

	// タイトル画面のメニューを生成
	m_pMenu = CTitleMenu::Create();
}