#include "mesh3D.h"

//==================================================================================
// --- メッシュ2Dの作成 ---
//==================================================================================
CMesh3D *CMesh3D::Create(const int nNumVtx, const int nNumIdx, const int nNumPrim)
{
	CMesh3D *pMesh3D = nullptr;		// 生成したメッシュ3Dへのポインタ
	HRESULT hr = S_OK;				// 初期化の判定

	// メッシュの生成
	pMesh3D = new CMesh3D;
	if (pMesh3D == nullptr)
	{ // 生成失敗時、nullを返す
		return nullptr;
	}

	// メッシュの初期化
	hr = pMesh3D->Init(nNumVtx, nNumIdx, nNumPrim);
	if (FAILED(hr))
	{ // 初期化失敗時、解放してnullを返す
		delete pMesh3D;
		return nullptr;
	}

	// 生成したメッシュを返す
	return pMesh3D;
}

