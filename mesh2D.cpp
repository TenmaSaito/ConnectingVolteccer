#include "mesh2D.h"

//==================================================================================
// --- メッシュ2Dの作成 ---
//==================================================================================
CMesh2D *CMesh2D::Create(const int nNumVtx, const int nNumIdx, const int nNumPrim)
{
	CMesh2D *pMesh2D = nullptr;		// 生成したメッシュ2Dへのポインタ
	HRESULT hr = S_OK;				// 初期化の判定

	// メッシュの生成
	pMesh2D = new CMesh2D;
	if (pMesh2D == nullptr)
	{ // 生成失敗時、nullを返す
		return nullptr;
	}

	// メッシュの初期化
	pMesh2D->Init(nNumVtx, nNumIdx, nNumPrim, sizeof(VERTEX_2D), FVF_VERTEX_2D);

	// 生成したメッシュを返す
	return pMesh2D;
}

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CMesh2D::CMesh2D()
{ // タイプを設定
	SetType(TYPE_MESH2D);
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CMesh2D::~CMesh2D()
{
}

//==================================================================================
// --- 初期化処理 ---
//==================================================================================
HRESULT CMesh2D::Init(const int nNumVtx, const int nNumIdx, const int nNumPrim, const size_t vtxSize, const DWORD dwFlags)
{
	HRESULT hr = S_OK;		// 処理判定

	// メッシュの初期化
	hr = CMesh::Init(nNumVtx, nNumIdx, nNumPrim, vtxSize, dwFlags);
	if (FAILED(hr))
	{ // メッシュの初期化
		return E_FAIL;
	}

	// 初期化結果を返す
	return S_OK;
}

//==================================================================================
// --- 終了処理 ---
//==================================================================================
void CMesh2D::Uninit(void)
{ // メッシュの終了
	CMesh::Uninit();
}

//==================================================================================
// --- 更新処理 ---
//==================================================================================
void CMesh2D::Update(void)
{
}

//==================================================================================
// --- 描画処理 ---
//==================================================================================
void CMesh2D::Draw(void)
{ // メッシュの描画
	CMesh::Draw();
}