#include "stateMachine.h"
#include "state.h"

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CStateMachine::CStateMachine()
{
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CStateMachine::~CStateMachine()
{
}

//==================================================================================
// --- ステートの変更処理 ---
//==================================================================================
void CStateMachine::ChangeState(std::unique_ptr<IState> pNext)
{
	if (m_pCurrentState != nullptr)
	{ // もし、既にステートがセットされていた場合、終了
		m_pCurrentState->OnExit();
		m_pCurrentState = nullptr;
	}

	// 新しいステートをセット
	m_pCurrentState = std::move(pNext);

	// 新しいステートを開始
	m_pCurrentState->OnEnter();
}

//==================================================================================
// --- ステートの更新処理 ---
//==================================================================================
void CStateMachine::Update(void)
{ // nullの時、スキップ
	if (m_pCurrentState == nullptr) return;

	// ステートがセットされていれば、更新
	m_pCurrentState->OnUpdate();
}