#include "stopwatch.h"

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CStopWatch::CStopWatch()
{
	// メンバ変数をクリア
	m_bRun = false;
	m_elapsed = std::chrono::nanoseconds(0);
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CStopWatch::~CStopWatch()
{
}

//==================================================================================
// --- 計測開始処理 ---
//==================================================================================
void CStopWatch::Start(void)
{
	if (m_bRun == true)
	{ // 既に計測を開始しているなら、終了
		return;
	}

	// 現在時刻を取得
	m_begin = m_end = std::chrono::system_clock::now();

	// 計測フラグを立てる
	m_bRun = true;
}

//==================================================================================
// --- 計測終了処理 ---
//==================================================================================
void CStopWatch::Stop(void)
{
	if (m_bRun == false)
	{ // 計測をしていないなら、終了
		return;
	}

	// 現在時刻を取得
	m_end = std::chrono::system_clock::now();

	// 合計時間をナノ秒に丸めて取得
	m_elapsed = m_elapsed + std::chrono::duration_cast<std::chrono::nanoseconds>(m_end - m_begin);

	// 計測フラグを下す
	m_bRun = false;
}

//==================================================================================
// --- 計測時間リセット処理 ---
//==================================================================================
void CStopWatch::Reset(void)
{
	// 合計時間を0にリセット
	m_elapsed = std::chrono::nanoseconds(0);

	// 計測開始、終了時間を現在時刻に設定
	m_begin = m_end = std::chrono::system_clock::now();
}

//==================================================================================
// --- 計測時間取得処理 (秒) ---
//==================================================================================
double CStopWatch::GetSeconds(void) const
{
	return GetElapsed<double, std::ratio<1>>();
}

//==================================================================================
// --- 計測時間取得処理 (ミリ秒) ---
//==================================================================================
double CStopWatch::GetMilliSeconds(void) const
{
	return GetElapsed<double, std::milli>();
}

//==================================================================================
// --- 計測時間取得処理 (ナノ秒) ---
//==================================================================================
long long CStopWatch::GetNanoSeconds(void) const
{
	return GetElapsed<long long, std::nano>();
}